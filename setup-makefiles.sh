#!/bin/bash
# Generate copy rules only after every listed source has been accounted for.
set -euo pipefail
SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ANDROID_ROOT=$(cd -- "$SCRIPT_DIR/../../.." && pwd)
VENDOR_DIR=${1:-$ANDROID_ROOT/vendor/lge/m1}
if [[ $# -gt 1 || ! -d "$VENDOR_DIR/proprietary" ]]; then
    echo "Usage: $0 [vendor/lge/m1 directory containing proprietary/]" >&2
    exit 1
fi
entries=()
declare -A seen=()
missing=0
while IFS= read -r entry; do
    entry=${entry%%#*}
    entry=$(printf '%s' "$entry" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
    [[ -z "$entry" ]] && continue
    if [[ "$entry" == -* || "$entry" == /* || "$entry" == *..* ]]; then
        echo "Unsupported or unsafe blob entry: $entry" >&2
        exit 1
    fi
    source=${entry%%:*}
    destination=${entry#*:}
    if [[ ! -f "$VENDOR_DIR/proprietary/$source" ]]; then
        echo "Missing proprietary source: $source" >&2
        missing=1
    fi
    pair="vendor/lge/m1/proprietary/$source:system/$destination"
    if [[ -z "${seen[$pair]+present}" ]]; then
        entries+=("$pair")
        seen[$pair]=1
    fi
done < "$SCRIPT_DIR/proprietary-blobs.txt"
if [[ $missing != 0 || ${#entries[@]} == 0 ]]; then
    echo "Generation stopped; existing vendor makefiles were preserved." >&2
    exit 1
fi
temporary=$(mktemp "$VENDOR_DIR/.m1-vendor-blobs.XXXXXX")
trap 'rm -f -- "$temporary"' EXIT
{
    printf '# Generated by device/lge/m1-common/setup-makefiles.sh\n\n'
    printf 'PRODUCT_COPY_FILES += \\\n'
    last=$((${#entries[@]} - 1))
    for index in "${!entries[@]}"; do
        printf '    %s' "${entries[$index]}"
        if [[ $index -lt $last ]]; then printf ' \\'; fi
        printf '\n'
    done
} > "$temporary"
mv -- "$temporary" "$VENDOR_DIR/m1-vendor-blobs.mk"
printf '%s\n' '# Generated by device/lge/m1-common/setup-makefiles.sh' \
    '$(call inherit-product, vendor/lge/m1/m1-vendor-blobs.mk)' > "$VENDOR_DIR/m1-vendor.mk"
